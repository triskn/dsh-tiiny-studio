// Build one browser module with no runtime dependency on the standalone 3D plugin.
// Fragments are separate lexical closures; combining them must not register multiple clients.
import fs from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import videoDraftTools from './ui/video-draft.part.js'
import historyFeedbackTools from './ui/history-feedback.part.js'
import previewProportionsTools from './ui/preview-proportions.part.js'

const fragments = await Promise.all(['media', 'three', 'studio'].map(name => fs.readFile(new URL(`./ui/${name}.part.js`, import.meta.url), 'utf8')))
const [media, three, studio] = fragments.map(s => s.trim())
const text = `/* Generated by build-client.mjs from ui/*.part.js; edit the sources instead. */\nwindow.__ModuleLoader__.load({\n  id: 'dsh-tiiny-video',\n  factory(require) {\n    const React = require('react')\n    const media = (${media})(React, (${videoDraftTools.toString()})(), (${historyFeedbackTools.toString()})(), (${previewProportionsTools.toString()})())\n    const three = (${three})(React)\n    return (${studio})(React, media, three)\n  },\n})\n`
const output = fileURLToPath(new URL('./client.js', import.meta.url))
if (process.argv.includes('--check')) {
  if (await fs.readFile(output, 'utf8') !== text) throw new Error('The Studio client is out of date. Run npm run build:client.')
} else await fs.writeFile(output, text)
